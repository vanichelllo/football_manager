'use strict';
const test = require('node:test');
const assert = require('node:assert');
const FM = require('../js/data/ukcase.js');

test('родовий відмінок українських імен', () => {
  const cases = {
    'Андрій Шевченко': 'Андрія Шевченка', 'Михайло Мудрик': 'Михайла Мудрика', 'Ілля Забарний': 'Іллі Забарного',
    'Олександр Зінченко': 'Олександра Зінченка', 'Микола Матвієнко': 'Миколи Матвієнка', 'Віктор Циганков': 'Віктора Циганкова',
    'Георгій Судаков': 'Георгія Судакова', 'Владислав Ванат': 'Владислава Ваната', 'Тарас Кравець': 'Тараса Кравця',
    'Дмитро Різник': 'Дмитра Різника', 'Артем Довбик': 'Артема Довбика', 'Олексій Гуцуляк': 'Олексія Гуцуляка',
    'Данило Ситник': 'Данила Ситника', 'Віталій Миколенко': 'Віталія Миколенка', 'Назар Волошин': 'Назара Волошина',
  };
  for (const [nom, gen] of Object.entries(cases)) assert.strictEqual(FM.ukGen(nom), gen, nom);
  assert.strictEqual(FM.ukGen('Kylian Mbappé'), null);
});
